//! `alpha-trustee-feed`: the one process of ours in a Trustee pod (PRD-02 deliverable 26,
//! `docs/trustee.md`). It runs beside Trustee v0.21.0's KBS, Attestation Service and RVPS, in
//! the same Kata TD, and is the pod's only door:
//!
//! - It attests the pod to alpha-kms as the Trustee App, like `alpha-runtime` does, and holds the
//!   leaf (`alpha_runtime::Runtime`).
//! - Before the three containers start it writes their configuration and keys ([`files`]):
//!   every listener on the TD's loopback, the KBS admin API on a key generated here, tokens signed
//!   with the Trustee App's derived key, resources served by this process alone.
//! - It installs what Trustee decides by, generated by alpha-kms, through the KBS admin API on
//!   loopback ([`admin`]), and installs the deny-all policy when that state is older than the
//!   platform document allows ([`gate::Feed::sync`]).
//! - It terminates the KBS's public TLS with a leaf alpha-kms issues it for the KBS's name and
//!   passes on only the attestation protocol and resource reads ([`gate`]). An attestation is
//!   passed back to the pod only once alpha-kms has admitted it; a resource is read only once
//!   alpha-kms has released it for that pod's token, and the KBS's resource backend then gets
//!   exactly that value, for exactly that request.

