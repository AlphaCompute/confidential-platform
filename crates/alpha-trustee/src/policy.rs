//! What Trustee decides by, generated: the KBS resource policy from the KMS's Revisions and
//! grants, and the Attestation Service's appraisal policies and the RVPS reference values from the
//! release-signed platform document. A Trustee pod installs exactly these through its KBS's admin
//! API on loopback; nobody writes them by hand.
//!
//! Each one is at most as permissive as the KMS's own rule for the same decision, so the two
//! verifiers agree in the one direction that matters: Trustee never admits what the KMS would
//! refuse. Where Rego cannot say what the KMS checks (dotted version minimums, the Revision's
//! signature chain), the KMS checks it again before it releases anything (`docs/trustee.md`).

