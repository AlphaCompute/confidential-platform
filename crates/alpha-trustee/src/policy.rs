/// The KBS policy that releases nothing: installed before the first state, and whenever the
/// state a pod holds is older than the platform document allows.
pub const DENY_ALL: &str = "package policy\n\ndefault allow := false\n";

/// The Attestation Service policy ids the KBS's gRPC client asks for: `default`, suffixed by the
/// device class (`attestation-service/src/ear_token/broker.rs`).
pub const AS_POLICY_CPU: &str = "default_cpu";
pub const AS_POLICY_GPU: &str = "default_gpu";

/// The RVPS reference value the CPU policy matches a TD's registers against.
pub const RV_KATA_TDX: &str = "alpha_kata_tdx";

/// NRAS's attestation API as Trustee's remote NVIDIA verifier calls it: it appends `/gpu`.
pub const NRAS_VERIFIER_PATH: &str = "/v4/attest";

/// A Revision v2 the resource policy admits: a registered, unrevoked Revision of an App with a
/// grant, whose MRCONFIGID the KMS has verified against its init-data.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Admitted {
    pub app: AppId,
    pub mrconfigid: Measurement,
    pub runtime_class: String,
    pub gpu: Option<GpuShape>,
    pub resources: Vec<GrantEntry>,
}

const HEADER: &str = "package policy\n\nimport rego.v1\n\n";

fn generated(by: &str) -> String {
    format!(
        "{HEADER}# Generated by alpha-kms ({by}). Do not edit: the Trustee pod's feed replaces it on every\n# refresh, and installs the deny-all policy when it cannot.\n\n"
    )
}

/// The KBS resource policy: `kbs:///<app>/<type>/<tag>` only to a token whose every submodule is
/// affirming, whose TD's MRCONFIGID is an admitted Revision's of that App, whose GPUs are exactly
/// that Revision's count of its model, and only what the App's grant names.
pub fn resource_policy(admitted: &[Admitted], gpu_policy: Option<&GpuPolicy>) -> String {
    let mut pods = BTreeMap::new();
    for a in admitted {
        let (count, hwmodels) = match &a.gpu {
            None => (0, Vec::new()),
            Some(shape) => (shape.count, hwmodels_of(gpu_policy, &shape.model)),
        };
        let resources: BTreeSet<&GrantEntry> = a.resources.iter().collect();
        pods.insert(
            hex::encode(a.mrconfigid.0),
            json!({
                "app": a.app,
                "runtime_class": a.runtime_class,
                "gpus": count,
                "hwmodels": hwmodels,
                "resources": resources,
            }),
        );
    }
    let mut out = generated("alpha_trustee::policy::resource_policy");
    out.push_str("default allow := false\n\n");
    out.push_str(&format!("pods := {}\n\n", Value::from_iter(pods)));
    out.push_str(
        r#"allow if {
	data.plugin == "resource"
	count(data["resource-path"]) == 3
	count(data.query) == 0
	not any_not_affirming
	pod := pods[input.submods.cpu0["ear.veraison.annotated-evidence"].init_data]
	pod.app == data["resource-path"][0]
	granted(pod.resources, data["resource-path"][1], data["resource-path"][2])
	count(gpu_submods) == pod.gpus
	not other_gpu_model(pod)
}

any_not_affirming if {
	some _, submod in input.submods
	submod["ear.status"] != "affirming"
}

gpu_submods contains name if {
	some name, _ in input.submods
	startswith(name, "gpu")
}

other_gpu_model(pod) if {
	some name in gpu_submods
	not input.submods[name]["ear.veraison.annotated-evidence"].nvidia.hwmodel in pod.hwmodels
}

granted(resources, kind, tag) if {
	some r in resources
	r.type == kind
	r.tag in {"*", tag}
}
"#,
    );
    out
}

/// NRAS's hardware model strings the policy maps to `model`, sorted.
fn hwmodels_of(policy: Option<&GpuPolicy>, model: &str) -> Vec<String> {
    policy
        .filter(|p| p.allowed_models.iter().any(|m| m == model))
        .map(|p| {
            p.hwmodels
                .iter()
                .filter(|(_, m)| *m == model)
                .map(|(hw, _)| hw.clone())
                .collect()
        })
        .unwrap_or_default()
}

const TRUST_CLAIMS: &str = r#"default executables := 33

default hardware := 97

default configuration := 36

default file_system := 0

default instance_identity := 0

default runtime_opaque := 0

default storage_opaque := 0

default sourced_data := 0

trust_claims := {
	"executables": executables,
	"hardware": hardware,
	"configuration": configuration,
	"file-system": file_system,
	"instance-identity": instance_identity,
	"runtime-opaque": runtime_opaque,
	"storage-opaque": storage_opaque,
	"sourced-data": sourced_data,
}

extensions := []

"#;

fn set_of<'a>(items: impl IntoIterator<Item = &'a String>) -> String {
    let items: BTreeSet<&String> = items.into_iter().collect();
    if items.is_empty() {
        return "set()".into();
    }
    let quoted: Vec<String> = items.iter().map(|s| json!(s).to_string()).collect();
    format!("{{{}}}", quoted.join(", "))
}

/// The TD's appraisal (`default_cpu`): genuine TDX at a TCB status and with advisories the
/// platform document's `policy` accepts, not debug, the init-data checked against MRCONFIGID,
/// and MRTD and RTMR0..2 one `kata-tdx` reference value of the document, all four together.
pub fn attestation_policy_cpu(doc: &PlatformDocument) -> String {
    let mut out = generated("alpha_trustee::policy::attestation_policy_cpu");
    out.push_str(TRUST_CLAIMS);
    out.push_str(&format!(
        r#"hardware := 2 if {{
	input.tdx
	input.tdx.quote.header.tee_type == "81000000"
	input.tdx.quote.header.vendor_id == "939a7233f79c4ca9940a0db3957f0607"
	input.tdx.tcb_status in {statuses}
	input.tdx.collateral_expiration_status == "0"
	not untolerated_advisory
}}

untolerated_advisory if {{
	some id in input.tdx.advisory_ids
	not id in {tolerated}
}}

configuration := 2 if {{
	input.tdx
	input.tdx.td_attributes.debug == false
	is_object(input.init_data_claims)
}}

executables := 3 if {{
	input.tdx
	some rv in query_reference_value("{RV_KATA_TDX}")
	rv.mr_td == input.tdx.quote.body.mr_td
	rv.rtmr_0 == input.tdx.quote.body.rtmr_0
	rv.rtmr_1 == input.tdx.quote.body.rtmr_1
	rv.rtmr_2 == input.tdx.quote.body.rtmr_2
}}
"#,
        statuses = set_of(&doc.policy.tcb_statuses),
        tolerated = set_of(&doc.policy.tolerated_advisories),
    ));
    out
}

/// `/a/b` as the Rego reference `input.nvidia["a"]["b"]`.
fn nvidia_ref(pointer: &str) -> Option<String> {
    if pointer.contains('~') {
        return None;
    }
    let segments: Vec<String> = pointer
        .strip_prefix('/')?
        .split('/')
        .map(|s| format!("[{}]", json!(s)))
        .collect();
    Some(format!("input.nvidia{}", segments.concat()))
}

/// Why the GPU policy admits no GPU, or `None` when Trustee can verify GPUs as the KMS does:
/// NRAS is the only verifier the document lists (Trustee runs no other), and the document names
/// the CC-mode claim and at least one hardware model.
pub fn gpu_refusal(doc: &PlatformDocument) -> Option<String> {
    let Some(policy) = &doc.gpu_policy else {
        return Some("the platform document has no gpu_policy".into());
    };
    if policy.verifiers != [GpuVerifierKind::Nras] {
        return Some(format!(
            "gpu_policy.verifiers is {:?}; Trustee verifies GPUs through NRAS alone",
            policy.verifiers
        ));
    }
    if policy.nras_cc_mode.is_none() {
        return Some("gpu_policy.nras_cc_mode names no CC-mode claim (G0 check)".into());
    }
    if policy.hwmodels.is_empty() {
        return Some("gpu_policy.hwmodels is empty".into());
    }
    None
}

/// A GPU's appraisal (`default_gpu`): every per-GPU NRAS claim the KMS's `nras` backend requires
/// (`alpha_attest::gpu::nras::claims::REQUIRED`), a hardware model the document maps to an
/// allowed model, and the document's CC-mode claim. With [`gpu_refusal`], no GPU is affirming.
pub fn attestation_policy_gpu(doc: &PlatformDocument) -> String {
    let mut out = generated("alpha_trustee::policy::attestation_policy_gpu");
    out.push_str(TRUST_CLAIMS);
    let policy = match (gpu_refusal(doc), &doc.gpu_policy) {
        (None, Some(policy)) => policy,
        (refusal, _) => {
            out.push_str(&format!(
                "# No GPU is affirming: {}.\n",
                refusal.unwrap_or_default()
            ));
            return out;
        }
    };
    let mut conditions = vec!["input.nvidia".to_owned()];
    let mut helpers = String::new();
    for (i, (pointer, expect)) in nras::claims::REQUIRED.iter().enumerate() {
        let Some(reference) = nvidia_ref(pointer) else {
            out.push_str(&format!("# No GPU is affirming: claim {pointer}.\n"));
            return out;
        };
        match expect {
            Expect::True => conditions.push(format!("{reference} == true")),
            Expect::Text(want) => conditions.push(format!("{reference} == {}", json!(want))),
            Expect::TrueIfPresent => {
                conditions.push(format!("not optional_{i}_not_true"));
                helpers.push_str(&format!(
                    "optional_{i}_not_true if {{\n\tv := {reference}\n\tv != true\n}}\n\n"
                ));
            }
        }
    }
    let allowed: BTreeSet<&String> = policy.allowed_models.iter().collect();
    let hwmodels = policy
        .hwmodels
        .iter()
        .filter(|(_, model)| allowed.contains(model))
        .map(|(hw, _)| hw);
    conditions.push(format!("input.nvidia.hwmodel in {}", set_of(hwmodels)));
    for name in nras::claims::TEXT {
        conditions.push(format!("is_string(input.nvidia[{}])", json!(name)));
    }
    if let Some(cc) = &policy.nras_cc_mode {
        match nvidia_ref(&cc.pointer) {
            Some(reference) => conditions.push(format!("{reference} == {}", cc.equals)),
            None => {
                out.push_str("# No GPU is affirming: the CC-mode claim's pointer.\n");
                return out;
            }
        }
    }
    out.push_str("verified if {\n");
    for c in &conditions {
        out.push_str(&format!("\t{c}\n"));
    }
    out.push_str("}\n\n");
    out.push_str(&helpers);
    out.push_str(
        "hardware := 2 if verified\n\nexecutables := 3 if verified\n\nconfiguration := 2 if verified\n",
    );
    out
}

/// The RVPS registration message (`rvps/src/lib.rs`, `sample` extractor) carrying every
/// `kata-tdx` reference value of the document as one tuple each.
pub fn reference_values(doc: &PlatformDocument) -> String {
    let values: BTreeSet<(String, String, String, String, String)> = doc
        .reference_values
        .iter()
        .filter(|rv| rv.kind == ReferenceKind::KataTdx)
        .filter_map(|rv| {
            Some((
                rv.runtime_class.clone()?,
                hex::encode(rv.values.mrtd.0),
                hex::encode(rv.values.rtmr0.0),
                hex::encode(rv.values.rtmr1.0),
                hex::encode(rv.values.rtmr2.0),
            ))
        })
        .collect();
    let tuples: Vec<Value> = values
        .into_iter()
        .map(|(class, mr_td, rtmr_0, rtmr_1, rtmr_2)| {
            json!({ "runtime_class": class, "mr_td": mr_td, "rtmr_0": rtmr_0,
                    "rtmr_1": rtmr_1, "rtmr_2": rtmr_2 })
        })
        .collect();
    let provenance = json!({ RV_KATA_TDX: tuples });
    json!({
        "version": "0.1.0",
        "type": "sample",
        "payload": BASE64_STANDARD.encode(provenance.to_string()),
    })
    .to_string()
}

/// The URL Trustee's remote NVIDIA verifier is configured with: the document's NRAS, NVIDIA's
/// when it names none.
pub fn nras_verifier_url(doc: &PlatformDocument) -> String {
    let base = doc
        .gpu_policy
        .as_ref()
        .and_then(|p| p.nras_url.as_deref())
        .unwrap_or(nras::DEFAULT_URL);
    format!("{}{NRAS_VERIFIER_PATH}", base.trim_end_matches('/'))
}

#[cfg(test)]
mod tests {
    use alpha_attest::{Policy, ReferenceMeasurements, ReferenceValue};
    use alpha_core::coco::{CPU_RUNTIME_CLASS, GPU_RUNTIME_CLASS};

    use super::*;
    use crate::resource::ResourceType;

    pub(crate) fn doc() -> PlatformDocument {
        let rv = |name: &str, class: Option<&str>, kind: ReferenceKind, byte: u8| ReferenceValue {
            name: name.into(),
            kind,
            runtime_class: class.map(Into::into),
            values: ReferenceMeasurements {
                mrtd: Measurement([byte; 48]),
                rtmr0: Measurement([byte.wrapping_add(1); 48]),
                rtmr1: Measurement([byte.wrapping_add(2); 48]),
                rtmr2: Measurement([byte.wrapping_add(3); 48]),
            },
        };
        let mut doc: PlatformDocument = serde_json::from_value(json!({
            "version": 4, "issued_at": "2026-12-01T00:00:00Z",
            "policy": { "tcb_statuses": ["UpToDate", "SWHardeningNeeded"], "tolerated_advisories": ["INTEL-SA-00837"] },
            "reference_values": [], "kms_ca_pem": "", "kms_revisions": [],
            "gpu_policy": {
                "allowed_models": ["B300"], "verifiers": ["nras"],
                "hwmodels": { "GB110 A01 GSP BROM": "B300", "GH100 A01 GSP BROM": "H100" },
                "nras_cc_mode": { "pointer": "/x-nvidia-gpu-cc-mode", "equals": "on" }
            }
        }))
        .unwrap();
        doc.reference_values = vec![
            rv(
                "kata-tdx/cpu",
                Some(CPU_RUNTIME_CLASS),
                ReferenceKind::KataTdx,
                0x10,
            ),
            rv(
                "nvidia/b300x8",
                Some(GPU_RUNTIME_CLASS),
                ReferenceKind::KataTdx,
                0x20,
            ),
            rv("prototype", None, ReferenceKind::PrototypeTdx, 0x30),
            rv("no class", None, ReferenceKind::KataTdx, 0x40),
        ];
        doc
    }

    fn admitted() -> Vec<Admitted> {
        let app: AppId = "01994b3e-5c8a-7d3e-9a1b-2c3d4e5f6a7b".parse().unwrap();
        vec![
            Admitted {
                app,
                mrconfigid: Measurement([0xaa; 48]),
                runtime_class: GPU_RUNTIME_CLASS.into(),
                gpu: Some(GpuShape {
                    count: 8,
                    model: "B300".into(),
                }),
                resources: vec![
                    GrantEntry {
                        kind: ResourceType::Secret,
                        tag: "db".into(),
                    },
                    GrantEntry {
                        kind: ResourceType::Key,
                        tag: "*".into(),
                    },
                ],
            },
            Admitted {
                app,
                mrconfigid: Measurement([0xbb; 48]),
                runtime_class: CPU_RUNTIME_CLASS.into(),
                gpu: None,
                resources: vec![GrantEntry {
                    kind: ResourceType::ImageKey,
                    tag: "base".into(),
                }],
            },
        ]
    }

    #[test]
    fn the_resource_policy_lists_each_admitted_init_data_with_its_app_gpus_and_grant() {
        let d = doc();
        let rego = resource_policy(&admitted(), d.gpu_policy.as_ref());
        assert!(rego.starts_with("package policy\n\nimport rego.v1\n"));
        assert!(rego.contains("default allow := false"));
        let pods_line = rego.lines().find(|l| l.starts_with("pods := ")).unwrap();
        let pods: Value = serde_json::from_str(pods_line.trim_start_matches("pods := ")).unwrap();
        let gpu_pod = &pods[hex::encode([0xaa; 48])];
        assert_eq!(gpu_pod["app"], "01994b3e-5c8a-7d3e-9a1b-2c3d4e5f6a7b");
        assert_eq!(gpu_pod["gpus"], 8);
        assert_eq!(gpu_pod["hwmodels"], json!(["GB110 A01 GSP BROM"]));
        assert_eq!(
            gpu_pod["resources"],
            json!([{ "type": "secret", "tag": "db" }, { "type": "key", "tag": "*" }])
        );
        let cpu_pod = &pods[hex::encode([0xbb; 48])];
        assert_eq!(cpu_pod["gpus"], 0);
        assert_eq!(cpu_pod["hwmodels"], json!([]));
        // Deterministic: the same state is the same policy.
        let mut reversed = admitted();
        reversed.reverse();
        assert_eq!(resource_policy(&reversed, d.gpu_policy.as_ref()), rego);
        // Nothing admitted, nothing released.
        let empty = resource_policy(&[], d.gpu_policy.as_ref());
        assert!(empty.contains("pods := {}"));
    }

    #[test]
    fn a_model_the_document_does_not_allow_maps_to_no_hardware_model() {
        let mut d = doc();
        d.gpu_policy.as_mut().unwrap().allowed_models = vec!["H100".into()];
        let rego = resource_policy(&admitted(), d.gpu_policy.as_ref());
        assert!(!rego.contains("GB110"));
        assert!(!resource_policy(&admitted(), None).contains("GB110"));
    }

    #[test]
    fn the_cpu_policy_pins_the_documents_tcb_policy_and_reference_values() {
        let rego = attestation_policy_cpu(&doc());
        assert!(rego.contains(r#"input.tdx.tcb_status in {"SWHardeningNeeded", "UpToDate"}"#));
        assert!(rego.contains(r#"not id in {"INTEL-SA-00837"}"#));
        assert!(rego.contains("input.tdx.td_attributes.debug == false"));
        assert!(rego.contains("is_object(input.init_data_claims)"));
        assert!(rego.contains(r#"query_reference_value("alpha_kata_tdx")"#));
        let mut strict = doc();
        strict.policy = Policy {
            tcb_statuses: vec!["UpToDate".into()],
            tolerated_advisories: vec![],
        };
        let rego = attestation_policy_cpu(&strict);
        assert!(rego.contains(r#"input.tdx.tcb_status in {"UpToDate"}"#));
        assert!(rego.contains("not id in set()"));
    }

    #[test]
    fn the_reference_values_are_the_documents_kata_tdx_tuples_only() {
        let message: Value = serde_json::from_str(&reference_values(&doc())).unwrap();
        assert_eq!(message["version"], "0.1.0");
        assert_eq!(message["type"], "sample");
        let provenance: Value = serde_json::from_slice(
            &BASE64_STANDARD
                .decode(message["payload"].as_str().unwrap())
                .unwrap(),
        )
        .unwrap();
        let tuples = provenance[RV_KATA_TDX].as_array().unwrap();
        assert_eq!(tuples.len(), 2);
        assert!(tuples.contains(&json!({
            "runtime_class": CPU_RUNTIME_CLASS, "mr_td": hex::encode([0x10; 48]),
            "rtmr_0": hex::encode([0x11; 48]), "rtmr_1": hex::encode([0x12; 48]),
            "rtmr_2": hex::encode([0x13; 48]) })));
        assert!(!provenance.to_string().contains(&hex::encode([0x30; 48])));
        assert!(!provenance.to_string().contains(&hex::encode([0x40; 48])));
    }

    #[test]
    fn the_gpu_policy_requires_every_claim_the_kms_requires() {
        let d = doc();
        assert_eq!(gpu_refusal(&d), None);
        let rego = attestation_policy_gpu(&d);
        for (pointer, _) in nras::claims::REQUIRED {
            assert!(rego.contains(&nvidia_ref(pointer).unwrap()), "{pointer}");
        }
        assert!(rego.contains(r#"input.nvidia["measres"] == "success""#));
        assert!(rego.contains(r#"input.nvidia.hwmodel in {"GB110 A01 GSP BROM"}"#));
        assert!(rego.contains(r#"input.nvidia["x-nvidia-gpu-cc-mode"] == "on""#));
        assert!(rego.contains("hardware := 2 if verified"));
        assert!(
            rego.contains(r#"v := input.nvidia["x-nvidia-gpu-attestation-report-cert-chain"]["x-nvidia-cert-ocsp-nonce-matches"]"#)
        );
    }

    #[test]
    fn without_a_gpu_policy_trustee_can_meet_no_gpu_is_affirming() {
        type Edit = Box<dyn Fn(&mut PlatformDocument)>;
        let cases: Vec<(Edit, &str)> = vec![
            (Box::new(|d| d.gpu_policy = None), "no gpu_policy"),
            (
                Box::new(|d| {
                    d.gpu_policy.as_mut().unwrap().verifiers =
                        vec![GpuVerifierKind::Nras, GpuVerifierKind::FortanixCcm]
                }),
                "NRAS alone",
            ),
            (
                Box::new(|d| d.gpu_policy.as_mut().unwrap().nras_cc_mode = None),
                "CC-mode",
            ),
            (
                Box::new(|d| d.gpu_policy.as_mut().unwrap().hwmodels.clear()),
                "hwmodels",
            ),
        ];
        for (edit, reason) in cases {
            let mut d = doc();
            edit(&mut d);
            assert!(gpu_refusal(&d).unwrap().contains(reason), "{reason}");
            let rego = attestation_policy_gpu(&d);
            assert!(rego.contains("# No GPU is affirming"), "{reason}");
            assert!(!rego.contains(":= 2 if"), "{reason}");
            assert!(!rego.contains(":= 3 if"), "{reason}");
        }
    }

    #[test]
    fn the_nras_url_is_the_documents_with_trustees_path() {
        let mut d = doc();
        assert_eq!(
            nras_verifier_url(&d),
            "https://nras.attestation.nvidia.com/v4/attest"
        );
        d.gpu_policy.as_mut().unwrap().nras_url = Some("https://nras.example/".into());
        assert_eq!(nras_verifier_url(&d), "https://nras.example/v4/attest");
    }
}
